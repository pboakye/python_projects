# Priority order used for sorting the shortlist — best matches first
MATCH_PRIORITY = {
    "Direct Match": 0,
    "Value Option (-1 Bed)": 1,
    "Stretch Budget Option": 2,
    "Upgrade Selection": 3,
}


def find_listings(listings, target_budget, target_beds):
    """
    Pure function: no printing, no input. Takes listings + buyer criteria,
    returns a list of matching listing dicts, each tagged with a
    'match_type' key, sorted by match priority then price.
    """
    stretch_budget = target_budget * 1.10
    buyer_shortlist = []

    for house in listings:
        match_type = None

        if house["beds"] == target_beds:
            if house["price"] <= target_budget:
                match_type = "Direct Match"
            elif house["price"] <= stretch_budget:
                match_type = "Stretch Budget Option"
        elif house["beds"] == target_beds + 1 and house["price"] <= stretch_budget:
            match_type = "Upgrade Selection"
        elif house["beds"] == target_beds - 1 and house["price"] <= target_budget:
            match_type = "Value Option (-1 Bed)"

        if match_type:
            tagged_house = house.copy()
            tagged_house["match_type"] = match_type
            buyer_shortlist.append(tagged_house)

    buyer_shortlist.sort(key=lambda h: (MATCH_PRIORITY[h["match_type"]], h["price"]))
    return buyer_shortlist


def display_matches(matches):
    """Handles all console output for a shortlist. Kept separate from matching logic."""
    if not matches:
        print("Sorry, No Properties Match Your Criteria Right Now.")
        return
    for house in matches:
        print(f" {house['match_type']}: {house['address']} "
              f"| Price: ${house['price']:,.2f} | Beds: {house['beds']} "
              f"| Agent: {house['agency_contact']}")


def save_shortlist_to_file(client_name, client_contact, target_budget, target_beds, matches):
    filename = f"{client_name.lower().replace(' ', '_')}_shortlist.txt"
    with open(filename, "w") as file:
        file.write("===========================================\n")
        file.write(f" REAL ESTATE SHORTLIST FOR: {client_name.upper()}\n")
        file.write("===========================================\n")
        file.write(f"Client Contact: {client_contact}\n")
        file.write(f"Target Budget: ${target_budget:,.2f}\n")
        file.write(f"Required Bedrooms: {target_beds}\n")
        file.write("-------------------------------------------\n")
        file.write("MATCHING PROPERTIES FOUND:\n\n")

        for idx, house in enumerate(matches, start=1):
            file.write(f"{idx}. [{house['match_type']}] {house['address']}\n")
            file.write(f"   Price:    ${house['price']:,.2f}\n")
            file.write(f"   Bedrooms: {house['beds']}\n")
            file.write(f"   Agent Contact: {house['agency_contact']}\n\n")

        file.write("===========================================\n")
        file.write("Report generated by Real Estate Assistant Bot\n")

    print(f"\n Success! Report saved to '{filename}'.")


def get_buyer_contact():
    while True:
        contact = input("What's the best phone number to reach you on? (e.g. 024 550 8082): ").strip()
        digits = "".join(c for c in contact if c.isdigit())
        if len(digits) >= 9:
            return contact
        print(" Please enter a valid phone number (at least 9 digits).")


